/* Draw one character, each font pixel becoming a sx-by-sy block. Characters
 * the font does not have are drawn as '?'. */
void font_draw_char_scaled(int x, int y, char c, uint32_t fg, uint32_t bg, int sx, int sy) {
    if (!fb.available) return;
    unsigned char idx = (unsigned char)c;
    if (idx >= FONT_CHAR_COUNT) idx = '?';
    const uint8_t *glyph = font_data[idx];

    int w = FONT_WIDTH * sx, h = FONT_HEIGHT * sy;
    int inside = x >= 0 && y >= 0 && x + w <= (int)fb.width && y + h <= (int)fb.height;

    if (inside && fb.draw) {
        /* Fast path: write straight into the buffer, one dirty mark per character */
        size_t stride = fb.pitch / 4;
        for (int gy = 0; gy < FONT_HEIGHT; gy++) {
            uint8_t bits = glyph[gy];
            uint32_t *row0 = fb.draw + (size_t)(y + gy * sy) * stride + (size_t)x;
            for (int gx = 0; gx < FONT_WIDTH; gx++) {
                uint32_t color = (bits & (1 << (7 - gx))) ? fg : bg;
                for (int px = 0; px < sx; px++) row0[gx * sx + px] = color;
            }
            for (int py = 1; py < sy; py++) {
                uint32_t *dst = row0 + (size_t)py * stride;
                for (int i = 0; i < w; i++) dst[i] = row0[i];
            }
        }
        fb_mark_dirty(x, y, w, h);
        return;
    }

    /* Partly off-screen: clipped, pixel by pixel */
    for (int gy = 0; gy < FONT_HEIGHT; gy++) {
        for (int gx = 0; gx < FONT_WIDTH; gx++) {
            uint32_t color = (glyph[gy] & (1 << (7 - gx))) ? fg : bg;
            fb_fill_rect(x + gx * sx, y + gy * sy, sx, sy, color);
        }
    }
}

void font_draw_char(int x, int y, char c, uint32_t fg, uint32_t bg) {
    font_draw_char_scaled(x, y, c, fg, bg, 1, 1);
}

void font_draw_string(int x, int y, const char *str, uint32_t fg, uint32_t bg) {
    int cx = x;
    while (*str) {
        font_draw_char(cx, y, *str, fg, bg);
        cx += FONT_WIDTH;
        str++;
    }
}
